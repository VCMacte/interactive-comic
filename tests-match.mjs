import { matchChoice, isSameUtterance } from './js/match.js';

const choices = [
  { label: 'Пять', keywords: ['пять', '5'] },
  { label: 'Четыре', keywords: ['четыре', '4'] },
  { label: 'Налево, к реке', keywords: ['налево', 'лево', 'река'] },
];

const cases = [
  [choices, 'пять', 'Пять'],
  [choices, '5', 'Пять'],
  [choices, 'думаю пять брёвен', 'Пять'],
  [choices, 'пядь', 'Пять'],                  // типичная ошибка распознавания
  [choices, 'четыре', 'Четыре'],
  [choices, 'пойдем налево', 'Налево, к реке'],
  [choices, 'к речке', 'Налево, к реке'],
  [choices, 'ПЯТЬ!', 'Пять'],
  [choices, '', null],
  [choices, 'абракадабра', null],
];

// Числа второго десятка. Движок Android отдаёт числительное цифрами, и
// раньше «12» попадало в вариант «два»: ключ «2» был подстрокой фразы.
// Найдено на ребёнке: верный ответ засчитывался промахом четыре раза
// подряд, после чего приходилось нажимать кнопку.
const NUM = ['ноль','один','два','три','четыре','пять','шесть','семь','восемь',
             'девять','десять','одиннадцать','двенадцать','тринадцать',
             'четырнадцать','пятнадцать','шестнадцать','семнадцать',
             'восемнадцать','девятнадцать','двадцать'];
const nums = (...ns) => ns.map(n => ({ label: NUM[n], keywords: [NUM[n], String(n)] }));

const teens = nums(2, 14, 12);
cases.push(
  [teens, 'двенадцать', 'двенадцать'],
  [teens, '12', 'двенадцать'],
  [teens, 'кажется двенадцать', 'двенадцать'],
  [teens, '14', 'четырнадцать'],
  [teens, 'два', 'два'],
  [teens, '2', 'два'],
  [nums(2, 20, 1), 'двадцать', 'двадцать'],
  [nums(2, 20, 1), '20', 'двадцать'],
  [nums(1, 11, 3), 'одиннадцать', 'одиннадцать'],
  [nums(1, 11, 3), '11', 'одиннадцать'],
  [nums(3, 13, 5), 'тринадцать', 'тринадцать'],
  [nums(3, 13, 5), '13', 'тринадцать'],
  [nums(5, 15, 7), 'пятнадцать', 'пятнадцать'],
  [nums(6, 16, 8), 'шестнадцать', 'шестнадцать'],
  [nums(7, 17, 9), 'семнадцать', 'семнадцать'],
  [nums(8, 18, 6), 'восемнадцать', 'восемнадцать'],
  [nums(9, 19, 7), 'девятнадцать', 'девятнадцать'],
);

// Любые два числа второго десятка не должны путаться между собой: ни словом,
// ни цифрой. Тройка вариантов собирается из соседей — промах здесь означает
// «верный ответ засчитан неверным».
for (let a = 10; a <= 20; a++) {
  for (let b = 10; b <= 20; b++) {
    if (a === b) continue;
    const pair = nums(a, b);
    cases.push([pair, NUM[a], NUM[a]], [pair, String(a), NUM[a]]);
  }
}

// Служебное слово внутри многословного ключа не ответ. Союз «и» лежит
// в ключах «шерсть и вода», «палки и уголёк», и сравнение по словам давало
// ему точное совпадение: услышанное «железо и» уезжало в «Шерсть и вода» —
// то есть в заведомо неверный вариант. Найдено по журналу от 23.10.2026.
const recipe = [
  { label: 'Шерсть и вода', keywords: ['шерсть и вода'] },
  { label: 'Палки и уголёк', keywords: ['палки и уголёк'] },
  { label: 'Железные слитки', keywords: ['железные слитки'] },
];
cases.push(
  [recipe, 'железо и', null],
  [recipe, 'железо и слитки', 'Железные слитки'],
  [recipe, 'а и', null],
  [recipe, 'шерсть и вода', 'Шерсть и вода'],
  [recipe, 'наверное палки и уголек', 'Палки и уголёк'],
  [recipe, 'железные слитки', 'Железные слитки'],
);

// Тот же предлог в начале обоих вариантов: услышанное «по» выбирало вариант
// порядком перебора, а не смыслом, — ребёнок мог сказать «по песку» и уехать
// на мост. Лучше не расслышать и спросить снова.
const ways = [
  { label: 'По мосту над лавой', keywords: ['мост', 'мосту', 'над лавой', 'лавой'] },
  { label: 'По песку', keywords: ['песок', 'песку', 'по песку', 'вдоль'] },
];
cases.push(
  [ways, 'по', null],
  [ways, 'а по', null],
  [ways, 'по мосту', 'По мосту над лавой'],
  [ways, 'мосту', 'По мосту над лавой'],
  [ways, 'по песку', 'По песку'],
  [ways, 'песку', 'По песку'],
);

// Распознавание Android отдаёт одну фразу нарастающими кусками, и каждый
// кусок приходит отдельным готовым результатом. Промах считался за каждый,
// поэтому постороннее «Мам я уже…» выжигало все четыре попытки сразу
// и сцена уходила на кнопки. Найдено по журналу от 23.10.2026.
const utt = [
  ['Мам', 'Мам я', true],
  ['Мам я', 'Мам я уже', true],
  ['Мам я уже', 'Мам я уже', true],
  ['какого', 'какого', true],
  ['девять', 'девять 12', true],
  ['спортзал на балке', 'спортзал на балке знаешь', true],
  ['три', 'шесть', false],
  ['три', 'тридцать', false],        // продолжение считается словами, не буквами
  ['', 'три', false],
  ['три', '', false],
  ['Мам я уже', 'Мам', false],       // назад не растут: это новая фраза
];
let failedUtt = 0;
for (const [prev, next, expected] of utt) {
  const got = isSameUtterance(prev, next);
  if (got !== expected) {
    failedUtt++;
    console.log(`FAIL  «${prev}» -> «${next}» продолжение? ${got} (ждали ${expected})`);
  }
}

let failed = 0;
for (const [list, input, expected] of cases) {
  const got = matchChoice(input, list)?.choice.label ?? null;
  const ok = got === expected;
  if (!ok) { failed++; console.log(`FAIL  "${input}" среди [${list.map(c => c.label)}] -> ${got}  (ждали ${expected})`); }
}
failed += failedUtt;
console.log(`проверок ${cases.length + utt.length}` + (failed ? `, провалено ${failed}` : ', все пройдены'));
process.exit(failed ? 1 : 0);
